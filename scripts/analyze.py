def cn_to_int(s):
    """中文数字（一至一百二十）-> int"""
    s = s.strip()
    if s.isdigit():
        return int(s)
    total, section, number = 0, 0, 0
    for ch in s:
        if ch in CN_NUM:
            number = CN_NUM[ch]
        elif ch == "十":
            section += (number if number else 1) * 10
            number = 0
        elif ch == "百":
            section += (number if number else 1) * 100
            number = 0
    return total + section + number


def split_chapters(text):
    """按行首 '第X回' 拆分为 120 章，返回 [(章号, 回目, 正文)]"""
    pat = re.compile(r"^第([一二三四五六七八九十百零〇\d]+)回\s*(.*)$", re.M)
    marks = list(pat.finditer(text))
    chapters = []
    for i, m in enumerate(marks):
        num = cn_to_int(m.group(1))
        title = m.group(2).strip()
        start = m.start()
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        chapters.append((num, title, text[start:end]))
    return chapters


def resolve_context(alias, text, s, e, chapter):
    """泛称归属判定，返回标准名或 None（不确定则丢弃，保证准确率）"""
    win = text[max(0, s - 14):s] + text[e:e + 14]
    if alias == "丞相":
        if any(h in win for h in CAO_HINTS):
            return "曹操"
        if any(h in win for h in ZHUGE_HINTS):
            return "诸葛亮"
        # 曹操卒于第78回；此后书中"丞相"多指诸葛亮
        return "诸葛亮" if chapter >= 79 else "曹操"
    if alias == "魏王":
        if any(h in win for h in PI_HINTS):
            return "曹丕"
        return "曹操"
    if alias == "陈留王":
        # 第 3-5 回的陈留王是后来即位的汉献帝刘协；全书末尾的陈留王是魏元帝曹奂
        return "献帝" if chapter <= 10 else "曹奂"
    if alias == "吴主":
        # 孙权之后，"吴主"依次为孙亮 / 孙休 / 孙皓
        if any(h in win for h in ("皓", "孙皓")):
            return "孙皓"
        if any(h in win for h in ("亮", "孙亮")):
            return "孙亮"
        if any(h in win for h in ("休", "孙休")):
            return "孙休"
        return "孙权" if chapter <= 107 else None
    if alias == "文帝":
        # "魏文帝"已整体匹配；裸"文帝"仅在曹丕身后（≥78 回）成立，避免误伤汉文帝
        return "曹丕" if chapter >= 78 else None
    return None


def main():
    raw = open(SRC, encoding="utf-8").read()
    text = raw
    for a, b in TEXT_FIX.items():
        text = text.replace(a, b)

    chapters = split_chapters(text)
    assert len(chapters) == 120, f"章节数异常: {len(chapters)}"
    assert [c[0] for c in chapters] == list(range(1, 121)), "章节序号异常"

    # 构建别名 -> 标准名，按长度降序
    alias2person = {}
    for person, (_, aliases) in CHARACTER_ALIASES.items():
        for a in aliases:
            alias2person[a] = person
    ordered = sorted(alias2person.keys(), key=lambda x: (-len(x), x))
    pattern = re.compile("|".join(re.escape(a) for a in ordered))

    # 逐章统计
    cumulative = defaultdict(int)
    chapter_data = []
    for num, title, body in chapters:
        counts = defaultdict(int)
        for m in pattern.finditer(body):
            alias = m.group(0)
            # 前一字阻断（天子建 / 主公明）
            if m.start() > 0 and alias[0] in BLOCK_PREV \
                    and body[m.start() - 1] in BLOCK_PREV[alias[0]]:
                continue
            # 后一字阻断（公明日 / 公明教）
            if alias[-1] in BLOCK_NEXT and m.end() < len(body) \
                    and body[m.end()] in BLOCK_NEXT[alias[-1]]:
                continue
            # 后随字排除（卧龙岗 / 卧龙冈）
            if alias in NEGATIVE_SUFFIX and m.end() < len(body) \
                    and body[m.end()] in NEGATIVE_SUFFIX[alias]:
                continue
            if alias in CONTEXT_ALIASES:
                person = resolve_context(alias, body, m.start(), m.end(), num)
                if person is None:
                    continue
            else:
                person = alias2person[alias]
            counts[person] += 1

        for p, c in counts.items():
            cumulative[p] += c
        chapter_data.append({
            "chapter": num,
            "title": title,
            "counts": dict(counts),
            "cumulative": dict(cumulative),
        })

    # 全书汇总
    total = dict(cumulative)
    ranking = sorted(total.items(), key=lambda kv: (-kv[1], kv[0]))

    # 曾进入 Top10 的人物（用于视频配色）
    ever = {}
    cum = defaultdict(int)
    for cd in chapter_data:
        for p, c in cd["counts"].items():
            cum[p] += c
        for p, v in sorted(cum.items(), key=lambda kv: (-kv[1], kv[0]))[:10]:
            ever[p] = max(ever.get(p, 0), v)

    out = {
        "meta": {
            "source": "《三国演义》全文（罗贯中，120 回）",
            "total_characters": len(text),
            "chapter_count": len(chapters),
            "tracked_characters": len(CHARACTER_ALIASES),
        },
        "characters": [
            {"name": n, "style": CHARACTER_ALIASES[n][0], "total": v}
            for n, v in ranking
        ],
        "ever_top10": [{"name": p, "peak": v}
                       for p, v in sorted(ever.items(), key=lambda kv: -kv[1])],
        "chapters": chapter_data,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False)

    print(f"章节数: {len(chapters)}  跟踪人物: {len(CHARACTER_ALIASES)}  全书提及总次: {sum(total.values())}")
    print("\n全书累计提及 Top 25：")
    for i, (n, v) in enumerate(ranking[:25], 1):
        print(f"{i:2d}. {n}({CHARACTER_ALIASES[n][0] or '-'})  {v}")

    print("\n曾进入章节 Top10 的人物（视频需配色）：")
    print("  " + "、".join(p for p, _ in sorted(ever.items(), key=lambda kv: -kv[1])))

    print("\n关键章节 Top10 快照：")
    for ch in (1, 5, 30, 37, 50, 76, 85, 104, 120):
        cum2 = defaultdict(int)
        for cd in chapter_data[:ch]:
            for p, c in cd["counts"].items():
                cum2[p] += c
        top = sorted(cum2.items(), key=lambda kv: (-kv[1], kv[0]))[:10]
        print(f"  第{ch:03d}回: " + " ".join(f"{p}{v}" for p, v in top))


